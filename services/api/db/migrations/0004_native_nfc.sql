-- Additive compatibility domain: never fabricates OIDC subjects, merchant ownership,
-- published partner programs, purchases, or redeemable partner rewards.
CREATE TABLE native_customers (
    id uuid PRIMARY KEY,
    username text UNIQUE NOT NULL CHECK (username ~ '^[a-z0-9._-]{3,40}$'),
    salt text NOT NULL CHECK (salt ~ '^[0-9a-f]{32}$'),
    password_hash text NOT NULL CHECK (password_hash ~ '^[0-9a-f]{128}$')
);
CREATE TABLE native_sessions (
    hash text PRIMARY KEY CHECK (hash ~ '^[0-9a-f]{64}$'),
    customer_id uuid NOT NULL REFERENCES native_customers(id),
    expires bigint NOT NULL
);
CREATE INDEX native_sessions_customer_idx ON native_sessions(customer_id);
CREATE TABLE native_cafes (
    id uuid PRIMARY KEY,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 200),
    target integer NOT NULL CHECK (target BETWEEN 3 AND 12)
);
CREATE TABLE native_tags (
    uid text PRIMARY KEY CHECK (uid ~ '^[0-9A-F]{14}$'),
    cafe_id uuid NOT NULL REFERENCES native_cafes(id),
    last_counter integer NOT NULL DEFAULT -1 CHECK (last_counter BETWEEN -1 AND 16777215)
);
CREATE TABLE native_cards (
    id uuid PRIMARY KEY,
    customer_id uuid NOT NULL REFERENCES native_customers(id),
    cafe_id uuid NOT NULL REFERENCES native_cafes(id),
    stamps integer NOT NULL CHECK (stamps BETWEEN 0 AND 12),
    rewards integer NOT NULL DEFAULT 0 CHECK (rewards >= 0),
    updated_at text NOT NULL,
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    UNIQUE(customer_id,cafe_id)
);
CREATE TABLE native_events (
    seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id uuid UNIQUE NOT NULL,
    customer_id uuid NOT NULL REFERENCES native_customers(id),
    request_id uuid NOT NULL,
    fingerprint text NOT NULL CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    card_id uuid NOT NULL REFERENCES native_cards(id),
    uid text NOT NULL REFERENCES native_tags(uid),
    counter integer NOT NULL CHECK (counter BETWEEN 0 AND 16777215),
    UNIQUE(customer_id,request_id),
    UNIQUE(uid,counter)
);
CREATE SEQUENCE native_wallet_change_seq;
CREATE TABLE native_wallet_passes (
    serial uuid PRIMARY KEY REFERENCES native_cards(id),
    token text NOT NULL CHECK (length(token) >= 16),
    revision uuid,
    version bigint NOT NULL DEFAULT -1,
    modified bigint NOT NULL DEFAULT 0,
    base_url text,
    change_tag bigint NOT NULL DEFAULT 0,
    bytes bytea,
    CHECK ((revision IS NULL AND bytes IS NULL) OR (revision IS NOT NULL AND bytes IS NOT NULL))
);
CREATE TABLE native_wallet_devices (
    device text PRIMARY KEY CHECK (length(device) BETWEEN 1 AND 200),
    push_token text NOT NULL CHECK (length(push_token) BETWEEN 32 AND 512 AND push_token ~ '^[0-9a-fA-F]+$')
);
CREATE TABLE native_wallet_registrations (
    device text NOT NULL REFERENCES native_wallet_devices(device) ON DELETE CASCADE,
    serial uuid NOT NULL REFERENCES native_wallet_passes(serial),
    PRIMARY KEY(device,serial)
);
CREATE TABLE native_wallet_jobs (
    device text PRIMARY KEY REFERENCES native_wallet_devices(device) ON DELETE CASCADE,
    generation bigint NOT NULL,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt bigint NOT NULL DEFAULT 0
);
CREATE INDEX native_wallet_registrations_serial_idx ON native_wallet_registrations(serial);
CREATE INDEX native_wallet_jobs_due_idx ON native_wallet_jobs(next_attempt);
